// Reads the subsetted sign face and writes the two modules the renderer needs: its
// exact advance widths, and the font itself as a data URI.
//
// The font travels inside the SVG because a receipt is rasterised through an <img>,
// which cannot reach a stylesheet — and resvg, which prints headlessly, ignores
// @font-face entirely and is handed the same bytes as a buffer.
//
// The face is a subset of Ultra (Apache 2.0, licence beside the file), cut to the
// capitals, digits and punctuation a shop sign uses, and renamed so a machine with
// the original installed still draws the one we measured.
//
//   node scripts/generate-sign-font.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const FONT = resolve("src/assets/fonts/ultra-sign.ttf");
const FAMILY = "PetesPrinterSign";
const font = readFileSync(FONT);

function tables(buffer) {
  const found = new Map();
  const count = buffer.readUInt16BE(4);
  for (let index = 0; index < count; index += 1) {
    const record = 12 + index * 16;
    found.set(buffer.toString("ascii", record, record + 4), {
      offset: buffer.readUInt32BE(record + 8),
      length: buffer.readUInt32BE(record + 12),
    });
  }
  return found;
}

const table = tables(font);
const need = (tag) => {
  const entry = table.get(tag);
  if (!entry) throw new Error(`${FONT} has no ${tag} table.`);
  return entry.offset;
};

const unitsPerEm = font.readUInt16BE(need("head") + 18);
const capHeight = font.readInt16BE(need("OS/2") + 88) / unitsPerEm;
const glyphCount = font.readUInt16BE(need("maxp") + 4);
const longHorMetrics = font.readUInt16BE(need("hhea") + 34);

/** Advance width of one glyph id; the last entry repeats for monospaced tails. */
function advanceOf(glyph) {
  const hmtx = need("hmtx");
  const index = Math.min(glyph, longHorMetrics - 1);
  return font.readUInt16BE(hmtx + index * 4) / unitsPerEm;
}

/** Character code to glyph id, reading the format 4 subtable every subset carries. */
function characterMap() {
  const cmap = need("cmap");
  const subtables = font.readUInt16BE(cmap + 2);
  let best;
  for (let index = 0; index < subtables; index += 1) {
    const record = cmap + 4 + index * 8;
    const offset = cmap + font.readUInt32BE(record + 4);
    if (font.readUInt16BE(offset) === 4) best = offset;
  }
  if (best === undefined) throw new Error("The sign font has no format 4 cmap subtable.");

  const segments = font.readUInt16BE(best + 6) / 2;
  const ends = best + 14;
  const starts = ends + segments * 2 + 2;
  const deltas = starts + segments * 2;
  const ranges = deltas + segments * 2;
  const map = new Map();
  for (let segment = 0; segment < segments; segment += 1) {
    const end = font.readUInt16BE(ends + segment * 2);
    const start = font.readUInt16BE(starts + segment * 2);
    const delta = font.readInt16BE(deltas + segment * 2);
    const rangeOffset = font.readUInt16BE(ranges + segment * 2);
    if (start === 0xffff) continue;
    for (let code = start; code <= end; code += 1) {
      let glyph;
      if (rangeOffset === 0) {
        glyph = (code + delta) & 0xffff;
      } else {
        const at = ranges + segment * 2 + rangeOffset + (code - start) * 2;
        glyph = font.readUInt16BE(at);
        if (glyph !== 0) glyph = (glyph + delta) & 0xffff;
      }
      if (glyph > 0 && glyph < glyphCount) map.set(code, glyph);
    }
  }
  return map;
}

const advances = [...characterMap()]
  .filter(([code]) => code >= 0x20)
  .sort(([a], [b]) => a - b)
  .map(([code, glyph]) => [String.fromCodePoint(code), Math.round(advanceOf(glyph) * 1e4) / 1e4]);

const rows = [];
for (let index = 0; index < advances.length; index += 6) {
  rows.push(`  ${advances.slice(index, index + 6).map(([character, width]) => `${JSON.stringify(character)}: ${width}`).join(", ")},`);
}

writeFileSync("src/blocks/sign-metrics.ts", `/**
 * Advance widths of the sign face, in ems, read straight out of its hmtx table.
 * The arch sets its name edge to edge, so an estimate would either clip a long name
 * or leave a short one floating. These are exact.
 *
 * Generated by scripts/generate-sign-font.mjs — do not edit by hand.
 */
export const SIGN_CAP_HEIGHT = ${Math.round(capHeight * 1e4) / 1e4};
export const SIGN_FALLBACK_ADVANCE = 0.72;

export const SIGN_ADVANCES: Record<string, number> = {
${rows.join("\n")}
};
`);

writeFileSync("src/blocks/sign-font.ts", `/**
 * The sign face as a data URI, so it can ride inside a rasterised SVG.
 *
 * Generated by scripts/generate-sign-font.mjs — do not edit by hand.
 * Ultra, subsetted and renamed; Apache 2.0, see src/assets/fonts.
 */
export const SIGN_FAMILY = "${FAMILY}";
export const SIGN_FONT_DATA_URI = "data:font/ttf;base64,${font.toString("base64")}";
`);

console.log(`Generated sign metrics (${advances.length} glyphs, cap ${capHeight.toFixed(4)}em) and ${(font.length / 1024).toFixed(1)}KB of font data.`);
